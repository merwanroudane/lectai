# ترتيب الخيارات في بنك الأسئلة أعلاه متحيّز (الصحيح غالباً في الموضع الثاني).
# نخلطها خلطاً ثابتاً لكل سؤال — ثابت بين عمليات التشغيل حتى لا تتغيّر
# الإجابات المحفوظة في session_state عند إعادة الرسم.
def _shuffled(qi: int) -> tuple[list[str], int]:
    """تُعيد خيارات السؤال بعد خلط ثابت، مع موضع الإجابة الصحيحة الجديد."""
    _q, opts, correct, _e, _l = QUESTIONS[qi]
    order = list(range(len(opts)))
    random.Random(1000 + qi).shuffle(order)
    return [opts[i] for i in order], order.index(correct)


_ARABIC_DIGITS = str.maketrans("0123456789", "٠١٢٣٤٥٦٧٨٩")


