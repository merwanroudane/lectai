# ═══════════════════════════ 6. الجسر الملموس ═══════════════════════════

st.markdown("## ٦. الجسر الملموس: من OLS إلى Ridge و Lasso")

ui.section_intro(
    "أفضل طريقة لرؤية التحوّل ليست في نموذج غريب، بل في <b>أبسط تعديل</b> "
    "على النموذج الذي تعرفه. "
    "هنا تظهر فلسفة تعلّم الآلة كلها في سطر رياضي واحد.",
    accent=a,
)

st.markdown(
    r"""
**المربّعات الصغرى العادية — ما تعرفه:**

$$\hat{\beta}^{\,\text{OLS}} \;=\; \arg\min_{\beta}\; \sum_{i=1}^{n}\left(y_i - x_i^{\top}\beta\right)^2$$

**انحدار الحافة — Ridge:**

$$\hat{\beta}^{\,\text{Ridge}} \;=\; \arg\min_{\beta}\; \sum_{i=1}^{n}\left(y_i - x_i^{\top}\beta\right)^2 \;+\; \lambda \sum_{j=1}^{p}\beta_j^{2}$$

**لاسو — Lasso:**

$$\hat{\beta}^{\,\text{Lasso}} \;=\; \arg\min_{\beta}\; \sum_{i=1}^{n}\left(y_i - x_i^{\top}\beta\right)^2 \;+\; \lambda \sum_{j=1}^{p}\left|\beta_j\right|$$
"""
)

ui.callout(
    "good",
    "ماذا يعني الحدّ المُضاف فلسفياً؟",
    "الحدّ <code>λ·Σβ²</code> يُعاقب النموذج على <b>كِبَر معاملاته</b>. "
    "النتيجة: مُقدِّر <b>متحيّز عمداً</b> — وهو ما كان الإحصاء الكلاسيكي "
    "يتجنّبه بكل وسيلة. "
    "<br><br><b>لماذا نقبل التحيّز؟</b> "
    "لأن معيار الحكم تغيّر. نظرية غاوس-ماركوف تضمن أن <code>OLS</code> "
    "هو <b>أفضل مُقدِّر غير متحيّز خطّي</b>. "
    "لكن إن سمحنا بالتحيّز، فقد يوجد مُقدِّر <b>بخطأ تربيعي كلّي أقلّ</b>. "
    "<br><br>وهذا بالضبط ما أثبته <b>جيمس وستاين سنة ١٩٦١</b> — داخل "
    "الإحصاء نفسه، قبل تعلّم الآلة بعقود. "
    "<b>فكرة التنظيم ليست غريبة عن الإحصاء؛ هي إحدى أعمق نتائجه.</b>",
)

st.markdown(
    """
| الوجه | `OLS` | `Ridge` | `Lasso` |
|---|---|---|---|
| **التحيّز** | غير متحيّز | متحيّز عمداً | متحيّز عمداً |
| **التباين** | عالٍ عند `p` كبير أو خطّية مشتركة | منخفض | منخفض |
| **يعمل عند `p > n`؟** | ✕ لا (الحلّ غير وحيد) | ✓ نعم | ✓ نعم |
| **ينتقي المتغيّرات؟** | ✕ لا | ✕ لا (يُقلّص فقط) | ✓ نعم (يُصفّر معاملات) |
| **كيف يُختار `λ`؟** | — | تحقّق متقاطع | تحقّق متقاطع |
| **الفلسفة** | نموذج صحيح مُقدَّر بأفضل طريقة | نموذج مُقيَّد لتقليل الخطأ الكلّي | نموذج مُقيَّد يختار بنفسه |
"""
)

ui.callout(
    "warn",
    "ملاحظة منهجية مهمّة حول Lasso",
    "اختيار <code>λ</code> بالتحقّق المتقاطع يجعل المتغيّرات المُنتقاة "
    "<b>ناتجة عن البيانات</b>. "
    "لذلك <b>لا يجوز</b> أن تُقدِّر بعد ذلك نموذج <code>OLS</code> على "
    "المتغيّرات المنتقاة وتُبلغ عن قيم <code>p</code> كأنها عادية — "
    "هذه <b>مغالطة الاستدلال بعد الانتقاء</b> "
    "<code>Post-selection inference</code>. "
    "توجد طرق مُصحَّحة لها (مثل <code>Selective Inference</code> و"
    "<code>Debiased Lasso</code>)، لكنها ليست الممارسة الافتراضية.",
)

