def categories_with_counts() -> list[tuple[str, int]]:
    """التصنيفات مع عدد مصطلحات كل تصنيف."""
    out: dict[str, int] = {}
    for _, _, cat, _ in TERMS:
        out[cat] = out.get(cat, 0) + 1
    return [(c, out.get(c, 0)) for c in CATEGORIES]


def search(query: str, category: str | None = None) -> list[tuple[str, str, str, str]]:
    """بحث نصّي بسيط في العربية والإنجليزية والتعريف."""
    q = (query or "").strip().lower()
    rows = TERMS
    if category and category != "الكل":
        rows = [r for r in rows if r[2] == category]
    if not q:
        return list(rows)
    return [r for r in rows if q in r[0].lower() or q in r[1].lower() or q in r[3].lower()]
